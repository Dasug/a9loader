//! The per-build `dir -> pack` index (`dirindex.toml`) — the offline answer to
//! "which pack hosts an asset in this `dir`?" that `host = "auto"` resolves
//! against.
//!
//! A-Train 9's i.dat row carries a bare `name`, a `dir` (consumer grouping)
//! and an `(off, len)` that selects bytes in *whichever pack is loaded when the
//! name is queried* — there is no per-row pack tag. So the host pack of a NEW
//! asset is not a free choice: it must be the pack that is resident while the
//! asset's consumers run. The shipped rows encode exactly that timing, so we
//! recover it empirically: for every shipped row, decode every pack's buffer
//! and see which buffer holds a plausible payload at `(off, len)` (the
//! reference row-match method, aggregated per `dir`).
//!
//! The table is generated by `a9ml gen-dirindex` from a live install and ships
//! **embedded** in the loader (same `include_str!` pattern as `builds.toml`),
//! so there is no loose file next to the game and adding a build is a loader
//! build away:
//!
//! ```toml
//! [build."5.00.5634".names]           # exact shipped row name -> pack
//! "_t_..." = "vp"
//! [build."5.00.5634".dirs]            # dir -> pack (all rows verified in one)
//! "train\\h510" = "vp"
//! [build."5.00.5634".ambiguous]       # dir -> the packs its vanilla rows span
//! "museum" = ["ep", "vp"]
//! ```
//!
//! `names` is emitted only for rows whose `dir` is ambiguous (elsewhere the
//! `dir` lookup already answers) — that is where the exact-name step is
//! *useful*: it can rescue a single row from a dir-level ambiguity.
//!
//! Resolution order for `host = "auto"` (a row's host):
//! 1. exact `name -> pack`;
//! 2. exact `dir -> pack`;
//! 3. the LONGEST known dir PREFIX (`train\mytrain` → the `train\*` family);
//! 4. otherwise a **loud refusal** — a guessed host does not miss cleanly, it
//!    reads another pack's bytes (no per-row pack tag, no bounds check).
//!
//! An AMBIGUOUS `dir` (its shipped rows span packs ⇒ its consumers span boot
//! windows, so no single host can be correct) refuses at step 2, and an
//! ambiguous prefix refuses at step 3. Directory tables are per build.

use crate::ModError;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};

/// The dir index as shipped in this repository (`crates/a9-mod/dirindex.toml`).
pub fn embedded() -> &'static str {
    include_str!("../dirindex.toml")
}

#[derive(Deserialize, Serialize, Debug, Clone, Default)]
#[serde(deny_unknown_fields)]
pub struct DirIndex {
    pub build: BTreeMap<String, BuildIndex>,
}

/// One build's resolution tables (all keyed by the shipped i.dat values).
#[derive(Deserialize, Serialize, Debug, Clone, Default)]
#[serde(deny_unknown_fields)]
pub struct BuildIndex {
    /// exact shipped row name -> host pack (only where the name is *useful*,
    /// i.e. rows whose dir is ambiguous)
    #[serde(default)]
    pub names: BTreeMap<String, String>,
    /// dir -> host pack (every shipped row of the dir verified in one pack)
    #[serde(default)]
    pub dirs: BTreeMap<String, String>,
    /// dir -> the set of packs the dir's shipped rows span (a `host = "auto"`
    /// refusal); an empty list = no pack verified any row there
    #[serde(default)]
    pub ambiguous: BTreeMap<String, Vec<String>>,
}

pub fn parse(text: &str) -> Result<DirIndex, ModError> {
    toml::from_str(text).map_err(|e| ModError::Parse(format!("dirindex.toml: {e}")))
}

/// Parse the embedded index — used by the loader at boot and by `a9ml`; tests
/// keep the shipped file valid.
pub fn embedded_index() -> Result<DirIndex, ModError> {
    parse(embedded())
}

impl BuildIndex {
    /// `prefix -> the set of host packs of every known dir at or under it`.
    /// Built from both `dirs` and `ambiguous` so an ambiguous subtree poisons
    /// its prefixes (a new dir under it cannot be resolved to one host).
    fn prefixes(&self) -> BTreeMap<String, BTreeSet<String>> {
        let mut m: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
        let mut add = |dir: &str, pack: &str| {
            let parts: Vec<&str> = dir.split('\\').collect();
            for i in 1..=parts.len() {
                m.entry(parts[..i].join("\\"))
                    .or_default()
                    .insert(pack.to_string());
            }
        };
        for (d, p) in &self.dirs {
            add(d, p);
        }
        for (d, ps) in &self.ambiguous {
            for p in ps {
                add(d, p);
            }
        }
        m
    }

    /// Resolve the host pack for a row named `name` in `dir`.
    pub fn resolve(&self, name: &str, dir: &str) -> Result<String, String> {
        if let Some(p) = self.names.get(name) {
            return Ok(p.clone());
        }
        if let Some(p) = self.dirs.get(dir) {
            return Ok(p.clone());
        }
        if let Some(ps) = self.ambiguous.get(dir) {
            return Err(if ps.is_empty() {
                format!(
                    "dir {dir:?} has no verifiable host (no shipped row there matched a pack)"
                )
            } else {
                format!(
                    "dir {dir:?} is AMBIGUOUS — its shipped rows span packs [{}]; a single \
                     host cannot serve consumers that run in different boot windows",
                    ps.join(", ")
                )
            });
        }
        let pref = self.prefixes();
        let parts: Vec<&str> = dir.split('\\').collect();
        for i in (1..=parts.len()).rev() {
            let q = parts[..i].join("\\");
            if let Some(ps) = pref.get(&q) {
                if ps.len() == 1 {
                    return Ok(ps.iter().next().unwrap().clone());
                }
                return Err(format!(
                    "dir {dir:?}: the longest known prefix {q:?} is AMBIGUOUS — it spans \
                     packs [{}]",
                    ps.iter().cloned().collect::<Vec<_>>().join(", ")
                ));
            }
        }
        Err(format!(
            "dir {dir:?} is unknown (absent from the shipped dir index) and has no known \
             prefix"
        ))
    }
}

/// Resolve a `host = "auto"` asset against the embedded index for `build`.
/// `Err` is a loud refusal message (the caller logs it and skips the effect).
pub fn resolve_auto(index: &DirIndex, build: &str, name: &str, dir: &str) -> Result<String, String> {
    match index.build.get(build) {
        Some(b) => b.resolve(name, dir),
        None => Err(format!(
            "no dir index for build {build} (this loader build carries no dir->pack table \
             for it)"
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn idx() -> DirIndex {
        let text = r#"
[build."5.00.5634".names]
"_t_museum_ep.x" = "ep"

[build."5.00.5634".dirs]
"train\\h510" = "vp"
"structure\\crane" = "cp"
"base" = "mcp"

[build."5.00.5634".ambiguous]
"museum" = ["ep", "vp"]
"weird" = []
"mixed\\a" = ["cp", "vp"]
"#;
        parse(text).unwrap()
    }

    #[test]
    fn embedded_index_is_valid() {
        let i = embedded_index().unwrap();
        let b = i.build.get("5.00.5634").expect("the steam build entry");
        // the primary use case: the train family is unambiguous and vp
        assert_eq!(b.resolve("_t_whatever_new_a.x", "train\\mytrain").unwrap(), "vp");
        assert!(b.dirs.len() > 100, "real table, not a stub");
    }

    #[test]
    fn resolves_exact_name_then_dir_then_prefix() {
        let i = idx();
        let b = i.build.get("5.00.5634").unwrap();
        // 1. exact name (even inside an ambiguous dir)
        assert_eq!(b.resolve("_t_museum_ep.x", "museum").unwrap(), "ep");
        // 2. exact dir
        assert_eq!(b.resolve("anything.x", "train\\h510").unwrap(), "vp");
        // 3. longest known dir prefix: a brand-new dir under train\*
        assert_eq!(b.resolve("_t_new_a.x", "train\\mytrain").unwrap(), "vp");
        assert_eq!(b.resolve("_t_new_a.x", "train\\mytrain\\lod").unwrap(), "vp");
        // a deeper known dir also wins its own prefix
        assert_eq!(b.resolve("x.x", "structure\\crane\\extra").unwrap(), "cp");
    }

    #[test]
    fn refuses_unknown_ambiguous_and_ambiguous_prefix() {
        let i = idx();
        let b = i.build.get("5.00.5634").unwrap();
        // unknown dir with no known prefix
        let e = b.resolve("x.x", "nowhere\\at\\all").unwrap_err();
        assert!(e.contains("unknown"), "{e}");
        // ambiguous exact dir
        let e = b.resolve("x.x", "museum").unwrap_err();
        assert!(e.contains("AMBIGUOUS") && e.contains("ep") && e.contains("vp"), "{e}");
        // ambiguous prefix (the whole `mixed\*` subtree spans packs)
        let e = b.resolve("x.x", "mixed\\brand_new").unwrap_err();
        assert!(e.contains("prefix") && e.contains("AMBIGUOUS"), "{e}");
        // dir that matched no pack at all
        let e = b.resolve("x.x", "weird").unwrap_err();
        assert!(e.contains("no verifiable host"), "{e}");
    }

    #[test]
    fn unknown_build_refuses() {
        let e = resolve_auto(&idx(), "9.99.9999", "a.x", "train\\x").unwrap_err();
        assert!(e.contains("no dir index for build"), "{e}");
    }

    #[test]
    fn rejects_unknown_fields() {
        assert!(parse("[build.\"x\"]\nextra = 1\n").is_err());
        assert!(parse("[build.\"x\".dirs]\n\"d\" = \"vp\"\n[build.\"x\".dirs.weird]\n").is_err());
    }
}
